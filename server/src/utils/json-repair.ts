import { logger } from './logger';

/**
 * Extracts raw JSON substring from LLM response text,
 * removing <think> tags, markdown code blocks and external chatter.
 */
export function extractJsonBlock(rawText: string): string {
  let text = (rawText || '').trim();

  // Strip DeepSeek / MiniMax thinking tokens
  text = text.replace(/<think>[\s\S]*?<\/think>/gi, '').trim();

  if (!text) return '';

  // Look for ```json ... ``` or ``` ... ```
  const fencedMatch = text.match(/```(?:json)?\s*([\s\S]*?)\s*```/i);
  if (fencedMatch && fencedMatch[1]) {
    return fencedMatch[1].trim();
  }

  // Look for first { or [
  const objStart = text.indexOf('{');
  const arrStart = text.indexOf('[');

  if (objStart === -1 && arrStart === -1) {
    return text;
  }

  const start = objStart === -1 ? arrStart : arrStart === -1 ? objStart : Math.min(objStart, arrStart);
  return text.substring(start).trim();
}

/**
 * Cleans common syntax errors generated by LLMs in JSON output:
 * - Smart quotes
 * - Unescaped control characters
 * - Trailing commas
 * - Single-line and multi-line comments
 */
export function sanitizeJsonString(raw: string): string {
  let text = raw;

  // Replace smart quotes
  text = text
    .replace(/[\u201C\u201D\u201E\u201F\u00AB\u00BB]/g, '"')
    .replace(/[\u2018\u2019\u201A\u201B]/g, "'");

  // Remove JS-style comments (outside of string literals where possible)
  text = text.replace(/\/\*[\s\S]*?\*\//g, '');
  text = text.replace(/(^|[^:])\/\/[^\n\r]*/g, '$1');

  // Remove trailing commas before closing braces/brackets
  text = text.replace(/,\s*([}\]])/g, '$1');

  return text;
}

/**
 * Repairs unclosed strings, unescaped raw newlines inside strings,
 * and unbalanced brackets/braces from truncated LLM responses.
 */
export function repairTruncatedJson(jsonStr: string): string {
  let inString = false;
  let isEscaped = false;
  const stack: ('}' | ']')[] = [];
  let result = '';

  for (let i = 0; i < jsonStr.length; i++) {
    const char = jsonStr[i];

    if (inString) {
      if (isEscaped) {
        result += char;
        isEscaped = false;
      } else if (char === '\\') {
        result += char;
        isEscaped = true;
      } else if (char === '"') {
        result += char;
        inString = false;
      } else if (char === '\n') {
        // Unescaped literal newline inside a JSON string
        result += '\\n';
      } else if (char === '\r') {
        // Skip carriage returns
      } else if (char === '\t') {
        result += '\\t';
      } else {
        result += char;
      }
    } else {
      if (char === '"') {
        inString = true;
        result += char;
      } else if (char === '{') {
        stack.push('}');
        result += char;
      } else if (char === '[') {
        stack.push(']');
        result += char;
      } else if (char === '}' || char === ']') {
        if (stack.length > 0 && stack[stack.length - 1] === char) {
          stack.pop();
        }
        result += char;
      } else {
        result += char;
      }
    }
  }

  // If we ended while still inside an open string, close it
  if (inString) {
    result += '"';
  }

  // Remove any trailing comma or dangling colon before closing braces
  result = result.trimEnd().replace(/[,:]\s*$/, '');

  // Close any unclosed objects or arrays in reverse order
  while (stack.length > 0) {
    const closer = stack.pop()!;
    result += closer;
  }

  // Final cleanup of trailing commas that might have been formed
  result = result.replace(/,\s*([}\]])/g, '$1');

  return result;
}

/**
 * Attempts multiple heuristic repair strategies to parse JSON from LLM output.
 */
export function safeParseJson<T = any>(rawText: string): T {
  const block = extractJsonBlock(rawText);
  if (!block) {
    throw new Error('No se encontró contenido JSON en la respuesta del modelo.');
  }

  // Strategy 1: Direct parse
  try {
    return JSON.parse(block) as T;
  } catch (_) {
    // continue to next strategy
  }

  // Strategy 2: Sanitize quotes, comments and trailing commas
  const sanitized = sanitizeJsonString(block);
  try {
    return JSON.parse(sanitized) as T;
  } catch (_) {
    // continue to next strategy
  }

  // Strategy 3: Repair unescaped newlines & truncated brackets
  const repaired = repairTruncatedJson(sanitized);
  try {
    return JSON.parse(repaired) as T;
  } catch (err: any) {
    // Strategy 4: Find balanced root object if there is trailing garbage
    const firstBrace = sanitized.indexOf('{');
    if (firstBrace !== -1) {
      let depth = 0;
      let inStr = false;
      let esc = false;
      let endIdx = -1;

      for (let i = firstBrace; i < sanitized.length; i++) {
        const c = sanitized[i];
        if (inStr) {
          if (esc) esc = false;
          else if (c === '\\') esc = true;
          else if (c === '"') inStr = false;
        } else {
          if (c === '"') inStr = true;
          else if (c === '{') depth++;
          else if (c === '}') {
            depth--;
            if (depth === 0) {
              endIdx = i;
              break;
            }
          }
        }
      }

      if (endIdx !== -1) {
        try {
          return JSON.parse(sanitized.substring(firstBrace, endIdx + 1)) as T;
        } catch (_) {
          // fall through
        }
      }
    }

    logger.error(`[json-repair] Failed to parse JSON even after heuristic repair. Raw snippet: ${rawText.substring(0, 300)}...`);
    throw new Error(`JSON no válido en la respuesta del modelo: ${err.message}`);
  }
}

/**
 * Parses JSON with automatic LLM repair fallback if programmatic parsing fails.
 */
export async function parseJsonWithLLMRepair<T = any>(
  rawText: string,
  repairFn?: (prompt: string) => Promise<{ text: string }>
): Promise<T> {
  try {
    return safeParseJson<T>(rawText);
  } catch (firstErr: any) {
    if (!repairFn) {
      throw firstErr;
    }

    logger.warn(`[json-repair] ⚠️ Primer parseo falló (${firstErr.message}). Ejecutando auto-reparación con LLM...`);
    try {
      const repairPrompt = `Corrige el siguiente JSON malformado. Devuelve ÚNICAMENTE el objeto JSON válido, sin explicaciones, sin markdown y sin comentarios.\n\nJSON malformado:\n${rawText}`;
      const { text: repairedRaw } = await repairFn(repairPrompt);
      return safeParseJson<T>(repairedRaw);
    } catch (secondErr: any) {
      logger.error(`[json-repair] Auto-reparación LLM falló: ${secondErr.message}`);
      throw new Error(`No se pudo procesar la lección: ${firstErr.message}`);
    }
  }
}
